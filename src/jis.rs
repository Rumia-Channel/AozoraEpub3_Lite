/// Java `JisConverter.toCharString`: 面区点を文字列にする。
pub(crate) fn to_char_string(men: u32, ku: u32, ten: u32) -> Option<String> {
    match men {
        0 => MEN0.get(ten as usize).map(|value| (*value).to_owned()),
        1 => {
            if ku == 0 || ku >= 95 || ten == 0 {
                return None;
            }
            if ku <= 13 {
                return MEN1_13[ku as usize]
                    .get(ten as usize)
                    .filter(|value| !value.is_empty())
                    .map(|value| (*value).to_owned());
            }
            code_to_char_string(*MEN1[ku as usize].get(ten as usize)?)
        }
        2 => {
            if ku == 0 || ku >= 95 || ten == 0 {
                return None;
            }
            code_to_char_string(*MEN2[ku as usize].get(ten as usize)?)
        }
        _ => None,
    }
}

/// Java `codeToCharString`: 0 は無効。Java は BMP 外をサロゲートペア 2 文字で
/// 返すが、Rust の `char` は補助面をそのまま表せるため 1 文字で返す。
fn code_to_char_string(code: u32) -> Option<String> {
    if code == 0 {
        return None;
    }
    char::from_u32(code).map(String::from)
}
